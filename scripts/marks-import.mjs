/**
 * Replace (or add) a product's mark:
 *
 *   pnpm run marks:import <slug> <file.svg> [--name "Name"] [--motion draw|spin|turn|none]
 *   pnpm run marks:import --index        rebuild marks/registry.mjs only
 *
 * Converts the SVG (marks/svg-to-mark.mjs: geometry kept, colours dropped),
 * writes marks/<slug>.mjs, and rebuilds the registry. An existing mark keeps
 * its name, motion and icon ink unless the flags say otherwise. Release the
 * package and every product that reads the mark follows.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MarkImportError, svgToMark } from '../marks/svg-to-mark.mjs';

const DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'marks');
const NOT_MARKS = new Set(['index.mjs', 'registry.mjs', 'svg.mjs', 'svg-to-mark.mjs']);

/** @param {string} message */
function fail(message) {
  console.error(`\n✗ ${message}\n`);
  process.exit(1);
}

/** @param {string} name */
const option = (name) => {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
};

/** @param {string} slug */
const ident = (slug) => slug.replace(/-(\w)/g, (_, c) => c.toUpperCase());

export function registrySource(/** @type {string[]} */ slugs) {
  const sorted = [...slugs].sort();
  return [
    '/**',
    ' * Every mark, by fleet slug. GENERATED from the mark files in this folder by',
    ' * `pnpm run marks:import`; do not edit by hand.',
    ' */',
    ...sorted.map((s) => `import ${ident(s)} from './${s}.mjs';`),
    '',
    `export const MARKS = Object.freeze({ ${sorted
      .map((s) => (ident(s) === s ? s : `'${s}': ${ident(s)}`))
      .join(', ')} });`,
    '',
  ].join('\n');
}

/** @param {Record<string, unknown>} mark */
export function markSource(mark) {
  return (
    `/** ${mark.name}'s mark. GENERATED by \`pnpm run marks:import\`; ${mark.source}. */\n` +
    `export default /** @type {import('./types.mjs').MarkDefinition} */ (${JSON.stringify(mark, null, 2)});\n`
  );
}

/** Format a written file with the repository's Prettier, so `format:check` stays green. */
async function format(/** @type {string} */ path) {
  try {
    const prettier = await import('prettier');
    const config = (await prettier.resolveConfig(path)) ?? {};
    writeFileSync(
      path,
      await prettier.format(readFileSync(path, 'utf8'), { ...config, filepath: path }),
    );
  } catch {
    // Prettier absent: the file is valid as written.
  }
}

async function writeRegistry() {
  const slugs = readdirSync(DIR)
    .filter((f) => f.endsWith('.mjs') && !NOT_MARKS.has(f))
    .map((f) => f.slice(0, -4));
  writeFileSync(join(DIR, 'registry.mjs'), registrySource(slugs));
  await format(join(DIR, 'registry.mjs'));
  console.log(`wrote marks/registry.mjs (${slugs.length} marks: ${slugs.sort().join(', ')})`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--index')) {
    await writeRegistry();
    process.exit(0);
  }
  const args = process.argv
    .slice(2)
    .filter((a, i, all) => !a.startsWith('--') && !['--name', '--motion'].includes(all[i - 1]));
  const [slug, file] = args;
  if (!slug || !file)
    fail(
      'usage: pnpm run marks:import <slug> <file.svg> [--name "Name"] [--motion draw|spin|turn|none]',
    );
  if (!/^[a-z0-9][a-z0-9-]*$/.test(slug))
    fail(`"${slug}" is not a fleet slug: lowercase letters, digits and dashes`);
  const motion = option('motion');
  if (motion && !['draw', 'spin', 'turn', 'none'].includes(motion))
    fail(`--motion must be draw, spin, turn or none (got "${motion}")`);

  /** @type {Record<string, unknown> | undefined} */
  let previous;
  try {
    previous = (await import(join(DIR, `${slug}.mjs`))).default;
  } catch {
    previous = undefined;
  }
  let geometry;
  try {
    geometry = svgToMark(readFileSync(file, 'utf8'));
  } catch (error) {
    if (error instanceof MarkImportError) fail(`${basename(file)}: ${error.message}`);
    throw error;
  }
  const name =
    option('name') ??
    /** @type {string | undefined} */ (previous?.name) ??
    slug
      .split('-')
      .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
      .join(' ');
  const mark = {
    slug,
    name,
    source: `drawn — imported from ${basename(file)}`,
    motion: motion ?? previous?.motion ?? 'draw',
    ...(previous?.iconInk ? { iconInk: previous.iconInk } : {}),
    viewBox: geometry.viewBox,
    strokeWidth: geometry.strokeWidth,
    shapes: geometry.shapes,
  };
  writeFileSync(join(DIR, `${slug}.mjs`), markSource(mark));
  await format(join(DIR, `${slug}.mjs`));
  console.log(
    `wrote marks/${slug}.mjs (${mark.shapes.length} shapes, viewBox ${mark.viewBox.join(' ')})`,
  );
  for (const warning of geometry.warnings) console.warn(`  ! ${warning}`);
  await writeRegistry();
}
